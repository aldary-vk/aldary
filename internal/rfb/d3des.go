// deskey 对应 d3des.c 的 deskey()，edf 为 en0(加密) 或 de1(解密)。
func (d *d3des) deskey(key []byte, edf int) {
	var pc1m [56]byte
	var pcr [56]byte
	var kn [32]uint32

	for j := 0; j < 56; j++ {
		l := int(d3desPc1[j])
		m := l & 0x07
		if key[l>>3]&byte(d3desBytebit[m]) != 0 {
			pc1m[j] = 1
		} else {
			pc1m[j] = 0
		}
	}

	for i := 0; i < 16; i++ {
		var m, n int
		if edf == de1 {
			m = (15 - i) << 1
		} else {
			m = i << 1
		}
		n = m + 1
		kn[m] = 0
		kn[n] = 0

		for j := 0; j < 28; j++ {
			l := j + int(d3desTotrot[i])
			if l < 28 {
				pcr[j] = pc1m[l]
			} else {
				pcr[j] = pc1m[l-28]
			}
		}
		for j := 28; j < 56; j++ {
			l := j + int(d3desTotrot[i])
			if l < 56 {
				pcr[j] = pc1m[l]
			} else {
				pcr[j] = pc1m[l-28]
			}
		}
		for j := 0; j < 24; j++ {
			if pcr[d3desPc2[j]] != 0 {
				kn[m] |= d3desBigbyte[j]
			}
			if pcr[d3desPc2[j+24]] != 0 {
				kn[n] |= d3desBigbyte[j]
			}
		}
	}
	d.cookey(&kn)
}

// cookey 对应 d3des.c 的 cookey()。
func (d *d3des) cookey(raw1 *[32]uint32) {
	var dough [32]uint32
	cook := 0
	for i := 0; i < 16; i++ {
		raw0 := raw1[i*2]
		raw1v := raw1[i*2+1]
		dough[cook] = (raw0 & 0x00fc0000) << 6
		dough[cook] |= (raw0 & 0x00000fc0) << 10
		dough[cook] |= (raw1v & 0x00fc0000) >> 10
		dough[cook] |= (raw1v & 0x00000fc0) >> 6
		cook++
		dough[cook] = (raw0 & 0x0003f000) << 12
		dough[cook] |= (raw0 & 0x0000003f) << 16
		dough[cook] |= (raw1v & 0x0003f000) >> 4
		dough[cook] |= (raw1v & 0x0000003f)
		cook++
	}
	d.knL = dough
}

// des 对应 d3des.c 的 des()，加密/解密一个 8 字节块 (inplace)。
func (d *d3des) des(inblock []byte) []byte {
	work := d.scrunch(inblock)
	d.desfunc(&work, &d.knL)
	out := d.unscrun(work)
	return out
}

// scrunch 对应 d3des.c 的 scrunch()：8 字节 -> 2 个 uint32。
func (d *d3des) scrunch(in []byte) [2]uint32 {
	var into [2]uint32
	into[0] = uint32(in[0]) << 24
	into[0] |= uint32(in[1]) << 16
	into[0] |= uint32(in[2]) << 8
	into[0] |= uint32(in[3])
	into[1] = uint32(in[4]) << 24
	into[1] |= uint32(in[5]) << 16
	into[1] |= uint32(in[6]) << 8
	into[1] |= uint32(in[7])
	return into
}

// unscrun 对应 d3des.c 的 unscrun()：2 个 uint32 -> 8 字节。
func (d *d3des) unscrun(in [2]uint32) []byte {
	out := make([]byte, 8)
	out[0] = byte(in[0] >> 24)
	out[1] = byte(in[0] >> 16)
	out[2] = byte(in[0] >> 8)
	out[3] = byte(in[0])
	out[4] = byte(in[1] >> 24)
	out[5] = byte(in[1] >> 16)
	out[6] = byte(in[1] >> 8)
	out[7] = byte(in[1])
	return out
}

// desfunc 对应 d3des.c 的 desfunc()：Feistel 网络主体。
func (d *d3des) desfunc(block *[2]uint32, keys *[32]uint32) {
	leftt := block[0]
	right := block[1]

	work := ((leftt >> 4) ^ right) & 0x0f0f0f0f
	right ^= work
	leftt ^= (work << 4)
	work = ((leftt >> 16) ^ right) & 0x0000ffff
	right ^= work
	leftt ^= (work << 16)
	work = ((right >> 2) ^ leftt) & 0x33333333
	leftt ^= work
	right ^= (work << 2)
	work = ((right >> 8) ^ leftt) & 0x00ff00ff
	leftt ^= work
	right ^= (work << 8)
	right = ((right << 1) | ((right >> 31) & 1)) & 0xffffffff
	work = (leftt ^ right) & 0xaaaaaaaa
	leftt ^= work
	right ^= work
	leftt = ((leftt << 1) | ((leftt >> 31) & 1)) & 0xffffffff

	ki := 0
	for round := 0; round < 8; round++ {
		work = (right << 28) | (right >> 4)
		work ^= keys[ki]
		fval := d3desSP7[work&0x3f]
		fval |= d3desSP5[(work>>8)&0x3f]
		fval |= d3desSP3[(work>>16)&0x3f]
		fval |= d3desSP1[(work>>24)&0x3f]
		work = right ^ keys[ki+1]
		fval |= d3desSP8[work&0x3f]
		fval |= d3desSP6[(work>>8)&0x3f]
		fval |= d3desSP4[(work>>16)&0x3f]
		fval |= d3desSP2[(work>>24)&0x3f]
		leftt ^= fval
		work = (leftt << 28) | (leftt >> 4)
		work ^= keys[ki+2]
		fval = d3desSP7[work&0x3f]
		fval |= d3desSP5[(work>>8)&0x3f]
		fval |= d3desSP3[(work>>16)&0x3f]
		fval |= d3desSP1[(work>>24)&0x3f]
		work = leftt ^ keys[ki+3]
		fval |= d3desSP8[work&0x3f]
		fval |= d3desSP6[(work>>8)&0x3f]
		fval |= d3desSP4[(work>>16)&0x3f]
		fval |= d3desSP2[(work>>24)&0x3f]
		right ^= fval
		ki += 4
	}

	right = (right << 31) | (right >> 1)
	work = (leftt ^ right) & 0xaaaaaaaa
	leftt ^= work
	right ^= work
	leftt = (leftt << 31) | (leftt >> 1)
	work = ((leftt >> 8) ^ right) & 0x00ff00ff
	right ^= work
	leftt ^= (work << 8)
	work = ((leftt >> 2) ^ right) & 0x33333333
	right ^= work
	leftt ^= (work << 2)
	work = ((right >> 16) ^ leftt) & 0x0000ffff
	leftt ^= work
	right ^= (work << 16)
	work = ((right >> 4) ^ leftt) & 0x0f0f0f0f
	leftt ^= work
	right ^= (work << 4)

	block[0] = right
	block[1] = leftt
}